package com.itheima.demo01;

public class ValueDemo3 {
    public static void main(String[] args) {
//        数据类型
//        整数:
//        byte
        byte b = 10;
        System.out.println(b);//10
//        short
        short s = 20;
        System.out.println(s);//20
//        int
        int i = 30;
        System.out.println(i);//30
//        long
        //如果要定义一个long类型的整数值，必须在整数值后面加上L或者l
        long n = 40L;
        System.out.println(n);//40
        System.out.println("==============================");
//        浮点数:
//        float
//        注意:如果要定义一个float类型的浮点数值，必须在浮点数值后面加上F或者f
        float f = 3.14F;
        System.out.println(f);//3.14
//        double
        double d = 20.2;
        System.out.println(d);//20.2
//        char
        char c = '中';
        System.out.println(c);//中
//        boolean
//        true/false
        boolean o = false;
        System.out.println(o);//false
    }
}
